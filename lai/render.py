def fill_template(name: str, **values: str) -> str:
    """Substitute @KEY@ placeholders in a template; fail loudly on leftovers."""
    text = (TEMPLATES_DIR / name).read_text()
    body = values.pop("BODY", None)
    for key, value in {"BANNER": BANNER, **values}.items():
        text = text.replace(f"@{key}@", value)
    leftover = sorted(set(re.findall(r"@[A-Z_]+@", text)) - ({"@BODY@"} if body is not None else set()))
    if leftover:
        raise ValueError(f"template {name}: unfilled placeholders {leftover}")
    return text.replace("@BODY@", body) if body is not None else text


def env_wrapper(settings: Settings) -> str:
    return fill_template(
        "llama-env.sh",
        ONEAPI_SETVARS=shlex.quote(str(settings.oneapi_setvars)),
        LLAMA_SERVER=shlex.quote(str(settings.llama_server)),
    )


def vllm_launcher_script(model: Model, settings: Settings, repo_root: Path = REPO_ROOT) -> str:
    return fill_template(
        "vllm-launcher.sh",
        MODEL_ID=shlex.quote(model.id),
        MODEL_DIR=shlex.quote(str(settings.model_dir)),
        CONTEXT=str(model.context),
        REPO_ROOT=shlex.quote(str(repo_root)),
        BODY=(model.launcher or "").strip("\n"),  # the template supplies the final newline
    )


def systemd_unit(settings: Settings, swap_binary: str, swap_config: Path) -> str:
    listen = f"{settings.listen_host}:{settings.listen_port}"
    exec_start = f"{swap_binary} --config {swap_config} --listen {listen}"
    return fill_template("llama-swap.service", EXEC_START=exec_start, HOME=str(Path.home()))


