def opencode_config(registry: Registry) -> dict:
    settings = registry.settings
    config = {
        "$schema": "https://opencode.ai/config.json",
        "model": f"{OPENCODE_PROVIDER}/{settings.default_model}",
        "small_model": f"{OPENCODE_PROVIDER}/{settings.small_model}",
        "share": "disabled",
        "provider": {
            OPENCODE_PROVIDER: {
                "npm": "@ai-sdk/openai-compatible",
                "name": "llama-swap (local)",
                # baseURL must be inside `options`: at the provider root it is ignored
                # and requests go to undefined/chat/completions.
                "options": {"baseURL": f"{settings.base_url}/v1", "apiKey": "dummy"},
                "models": {m.id: opencode_model_entry(m) for m in registry.active()},
            }
        },
    }
    return deep_merge(config, settings.opencode_extra)


def opencode_model_entry(model: Model) -> dict:
    entry: dict = {
        "name": model.name,
        # opencode compacts based on limit.context, so it must be what one request
        # actually gets from the server, not the total -c.
        "limit": {"context": model.slot_context, "output": model.max_output},
    }
    if model.reasoning_field:
        # Without this, a turn that only reasons renders as a blank response.
        entry["reasoning"] = True
        entry["interleaved"] = {"field": model.reasoning_field}
    if model.vision:
        # opencode silently strips image parts for custom openai-compatible models
        # unless `modalities` says otherwise (undocumented); `attachment` alone is
        # not enough, so both are set.
        entry["attachment"] = True
        entry["modalities"] = {"input": ["text", "image"], "output": ["text"]}
    return entry


def deep_merge(base: dict, override: dict) -> dict:
    """A copy of `base` with `override` merged in: nested dicts merge, anything else replaces."""
    merged = dict(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(merged.get(key), dict):
            merged[key] = deep_merge(merged[key], value)
        else:
            merged[key] = value
    return merged
