def llama_server_args(model: Model, settings: Settings, weights: str, mmproj: str | None) -> list[list[str]]:
    """llama-server arguments as groups of tokens: one group per line of the YAML
    `cmd` block, flattened for `lai run`. `${PORT}` is llama-swap's macro."""
    groups = [
        ["--port", "${PORT}"],
        ["--host", settings.listen_host],
        ["-a", model.id],
        ["-m", weights],
    ]
    if mmproj:
        groups.append(["--mmproj", mmproj])
    if model.device:
        groups.append(["--device", model.device])
    groups.append(["-ngl", str(model.gpu_layers)])
    groups.append(["-sm", model.split_mode])
    if model.cpu_moe_layers:
        groups.append(["--n-cpu-moe", str(model.cpu_moe_layers)])
    if model.load_mode:
        groups.append(["--load-mode", model.load_mode])
    groups.append(["-c", str(model.context)])
    groups.append(["-ub", str(model.ubatch), "-b", str(model.batch)])
    groups.append(["--parallel", str(model.parallel)])
    groups.append(["-fa", model.flash_attn])
    if model.kv_type:
        groups.append(["-ctk", model.kv_type, "-ctv", model.kv_type])
    groups.append(["--jinja"])  # without it tool calls come back as prose
    groups += [[f"--{key.replace('_', '-')}", str(value)] for key, value in model.sampler.items()]
    groups += group_flags(model.extra_args)
    return groups


def group_flags(tokens: list[str]) -> list[list[str]]:
    """Group a flat argv into [flag, values...] so each flag reads on its own line."""
    groups: list[list[str]] = []
    for token in tokens:
        starts_flag = token.startswith("-") and not re.fullmatch(r"-\d+(\.\d+)?", token)
        if starts_flag or not groups:
            groups.append([token])
        else:
            groups[-1].append(token)
    return groups


_SHELL_SAFE = re.compile(r"[A-Za-z0-9_@%+=:,./-]+|\$\{[A-Z_]+\}")


def shell_join(tokens: list[str]) -> str:
    """Join tokens for a llama-swap `cmd` line, which is split like a shell would.
    Quotes only when needed, and leaves llama-swap macros such as ${PORT} bare."""
    return " ".join(t if _SHELL_SAFE.fullmatch(t) else shlex.quote(t) for t in tokens)


