def llama_swap_config(registry: Registry, host: Host, gen_dir: Path) -> str:
    settings = registry.settings
    document = {
        "healthCheckTimeout": settings.health_timeout_s,
        "startPort": settings.backend_start_port,
        "globalTTL": settings.idle_ttl_s,
        "logLevel": "info",
        "logToStdout": "both",
        "sendLoadingState": True,
        "includeAliasesInList": False,
        "store": {"path": str(settings.activity_db)},
        "models": {m.id: swap_model_entry(m, settings, host, gen_dir) for m in registry.active()},
        "routing": {"router": coresidency_router(registry)},
    }
    header = "\n".join([
        BANNER,
        f"yaml-language-server: $schema={SWAP_SCHEMA}",
        "",
        "Co-residency: models pinned to different cards may be loaded together (one",
        "per card). Models pinned to no card appear in no matrix set, which llama-swap",
        "treats as run-alone: loading one evicts everything else.",
    ])
    return yamlout.dump(document, header=header)


def swap_model_entry(model: Model, settings: Settings, host: Host, gen_dir: Path) -> dict:
    entry: dict = {"name": model.name}
    if model.notes:
        entry["description"] = model.notes
    entry["cmd"] = backend_command(model, settings, host, gen_dir)
    entry["ttl"] = model.ttl if model.ttl is not None else -1  # -1: use globalTTL
    entry["capabilities"] = {
        "tools": model.tools,
        "context": model.slot_context,
        "in": ["text", "image"] if model.vision else ["text"],
        "out": ["text"],
    }
    if model.request_params:
        entry["setParams"] = model.request_params
    return entry


def backend_command(model: Model, settings: Settings, host: Host, gen_dir: Path) -> str:
    """The `cmd` block: wrapper + llama-server args, or the vLLM launcher."""
    if model.engine == "vllm":
        return f"{vllm_launcher(gen_dir, model.id)} ${{PORT}}"
    weights = host.find(model.weights) or f"MISSING:{settings.model_dir / model.weights}"
    mmproj = host.find(model.mmproj) if model.mmproj else None
    lines = [str(gen_dir / "llama-env.sh")]
    lines += [shell_join(group) for group in llama_server_args(model, settings, weights, mmproj)]
    return "\n".join(lines) + "\n"


def coresidency_router(registry: Registry) -> dict:
    """llama-swap's matrix router: at most one pinned model per card at a time.

    Each card's models become an OR group, groups are ANDed, and llama-swap
    treats any subset of a set as valid. Unpinned models are in no set, so
    they run alone. With fewer than two populated cards nothing can co-reside
    and the default group router applies.
    """
    groups = [
        registry.pinned_to(card) for card in registry.settings.cards if registry.pinned_to(card)
    ]
    if len(groups) < 2:
        return {"use": "group"}
    variables: dict[str, str] = {}
    evict_costs: dict[str, int] = {}
    expressions = []
    for letter, models in zip("abcdefghijklmnopqrstuvwxyz", groups, strict=False):
        names = []
        for index, model in enumerate(models):
            name = f"{letter}{index}"  # matrix vars must be 1-8 alphanumerics
            variables[name] = model.id
            evict_costs[name] = max(1, int(model.vram_gb))  # bigger reloads cost more
            names.append(name)
        expressions.append(f"({' | '.join(names)})")
    return {
        "use": "matrix",
        "settings": {
            "matrix": {
                "vars": variables,
                "evict_costs": evict_costs,
                "sets": {"coresident": " & ".join(expressions)},
            }
        },
    }


