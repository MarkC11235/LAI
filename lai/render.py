"""`lai gen`: turn the registry into the files the stack runs on.

Everything here is a pure function of (registry, host lookups): no writes, no
network. `artifacts()` is the whole output of `lai gen`; cli.py only writes it.

    gen/llama-swap.yaml    one entry per enabled model + the co-residency matrix
    gen/llama-env.sh       environment wrapper every llama-server starts through
    gen/vllm-<id>.sh       container launcher per engine="vllm" model
    gen/opencode.json      client config, installed to Settings.opencode_config

Because the proxy config and the client config come from the same registry, a
model's routing key cannot drift between them. That drift has no error message:
llama-server ignores the request's `model` field and answers anyway, so the
symptom is fluent output from the wrong model.
"""

from __future__ import annotations

import json
import re
import shlex
from dataclasses import dataclass
from pathlib import Path

from lai import yamlout
from lai.host import Host
from lai.paths import REPO_ROOT, TEMPLATES_DIR, vllm_launcher
from lai.registry import Registry
from lai.schema import Model, Settings

BANNER = "GENERATED by `lai gen` from models.py. Do not edit: changes are overwritten."
SWAP_SCHEMA = "https://raw.githubusercontent.com/mostlygeek/llama-swap/refs/heads/main/config-schema.json"
OPENCODE_PROVIDER = "llamacpp"  # opencode model refs are "llamacpp/<id>"; renaming breaks saved sessions


@dataclass(frozen=True)
class Artifact:
    path: Path
    content: str
    executable: bool = False


def artifacts(registry: Registry, host: Host, gen_dir: Path) -> list[Artifact]:
    """Every file `lai gen` writes, in write order."""
    settings = registry.settings
    files = [
        Artifact(gen_dir / "llama-swap.yaml", llama_swap_config(registry, host, gen_dir)),
        Artifact(gen_dir / "llama-env.sh", env_wrapper(settings), executable=True),
    ]
    files += [
        Artifact(vllm_launcher(gen_dir, m.id), vllm_launcher_script(m, settings), executable=True)
        for m in registry.active()
        if m.engine == "vllm"
    ]
    opencode = json.dumps(opencode_config(registry), indent=2, ensure_ascii=False) + "\n"
    files.append(Artifact(gen_dir / "opencode.json", opencode))
    return files


